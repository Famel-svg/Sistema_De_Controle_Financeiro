-- Esquema inicial da API (PostgreSQL; também roda no H2 em modo PostgreSQL usado nos testes).
-- Substitui T_CLIENTE, T_RECEITA e T_GASTOS do Oracle: receitas e gastos tinham as mesmas
-- colunas e passam a viver numa única tabela de lançamentos, distinguidos pela coluna tipo.

CREATE TABLE cliente (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(254) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    CONSTRAINT uk_cliente_email UNIQUE (email)
);

CREATE TABLE lancamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT         NOT NULL,
    tipo             VARCHAR(10)    NOT NULL,
    nome             VARCHAR(120)   NOT NULL,
    descricao        VARCHAR(500)   NOT NULL,
    valor            NUMERIC(15, 2) NOT NULL,
    data_lancamento  DATE           NOT NULL,
    CONSTRAINT fk_lancamento_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE CASCADE,
    CONSTRAINT ck_lancamento_tipo CHECK (tipo IN ('RECEITA', 'GASTO')),
    CONSTRAINT ck_lancamento_valor_positivo CHECK (valor > 0)
);

CREATE INDEX idx_lancamento_cliente_tipo_data ON lancamento (cliente_id, tipo, data_lancamento);
